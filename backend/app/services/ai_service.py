# =========================================================
# REPETITION CLEANUP
# =========================================================

def clean_repeated_output(answer: str) -> str:
    """
    Remove obvious consecutive word or phrase loops generated by AI.
    Preserve the original meaning and language.
    """

    if not answer:
        return ""

    answer = answer.strip()

    tokens = answer.split()

    if len(tokens) < 4:
        return answer

    def normalize(token):
        return re.sub(
            r"[^\w]",
            "",
            token,
            flags=re.UNICODE
        ).casefold()

    result = []
    index = 0

    while index < len(tokens):

        repetition_found = False

        max_phrase_size = min(
            8,
            (len(tokens) - index) // 3
        )

        # Detect a phrase repeated three or more times.
        for phrase_size in range(max_phrase_size, 1, -1):

            phrase = [
                normalize(word)
                for word in tokens[index:index + phrase_size]
            ]

            if not any(phrase):
                continue

            repetitions = 1

            while True:

                next_index = (
                    index + repetitions * phrase_size
                )

                if next_index + phrase_size > len(tokens):
                    break

                next_phrase = [
                    normalize(word)
                    for word in tokens[
                        next_index:next_index + phrase_size
                    ]
                ]

                if next_phrase == phrase:
                    repetitions += 1
                else:
                    break

            if repetitions >= 3:

                result.extend(
                    tokens[index:index + phrase_size]
                )

                index += repetitions * phrase_size
                repetition_found = True
                break

        if repetition_found:
            continue

        # Detect a single word repeated four or more times.
        current_word = normalize(tokens[index])

        if current_word:

            repetitions = 1

            while (
                index + repetitions < len(tokens)
                and normalize(tokens[index + repetitions])
                == current_word
            ):
                repetitions += 1

            if repetitions >= 4:

                result.append(tokens[index])
                index += repetitions
                continue

        result.append(tokens[index])
        index += 1

    cleaned = " ".join(result).strip()

    # Keep the response short.
    sentences = re.split(
        r"(?<=[.!?।])\s+",
        cleaned
    )

    if len(sentences) > 2:
        cleaned = " ".join(sentences[:2])

    return cleaned.strip()


# =========================================================
# ASK AI
# =========================================================

def ask_ai(
    prompt: str,
    language: str = "English"
) -> str:

    language_rule = LANGUAGE_RULES.get(
        language,
        LANGUAGE_RULES["English"]
    )

    payload = {
        "model": MODEL,

        "messages": [
            {
                "role": "system",
                "content": (
                    SYSTEM_INSTRUCTIONS
                    + "\n\nMANDATORY LANGUAGE:\n"
                    + language_rule
                ),
            },
            {
                "role": "user",
                "content": prompt,
            },
        ],

        "stream": False,
        "think": False,
        "options": {
            "temperature": 0.2,
            "top_p": 0.85,
            "top_k": 40,

            # Reduce repeated words and phrases.
            "repeat_penalty": 1.2,
            "repeat_last_n": 128,

            # Prevent unnecessarily long answers.
            "num_predict": 120,
        },
    }

    request = urllib.request.Request(
        OLLAMA_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Content-Type": "application/json"
        },
        method="POST",
    )

    try:

        with urllib.request.urlopen(
            request,
            timeout=300
        ) as response:

            result = json.loads(
                response.read().decode("utf-8")
            )

        message = result.get("message", {})

        answer = (
            message.get("content", "").strip()
            if isinstance(message, dict)
            else ""
        )

        if not answer:

            print("OLLAMA returned an empty answer.")

            return "I couldn't generate a response."

        # Remove obvious generation loops.
        answer = clean_repeated_output(answer)

        if not answer:
            return "I couldn't generate a response."

        return answer

    except urllib.error.HTTPError as error:

        error_body = error.read().decode(
            "utf-8",
            errors="replace"
        )

        print("OLLAMA HTTP ERROR:", error_body)

        raise Exception(
            f"Ollama returned HTTP {error.code}"
        ) from error

    except urllib.error.URLError as error:

        print("OLLAMA CONNECTION ERROR:", error)

        raise Exception(
            f"Cannot connect to Ollama: {error}"
        ) from error

    except Exception as error:

        print("OLLAMA ERROR:", error)

        raise